-- vw_Compras_FacturasPendientes
-- Facturas, ND y NC de proveedores genuinamente pendientes de pago.
-- Saldo real = TOTAL - suma de imputaciones/pagos con FONDO<>'0' (excluye ajustes contra otras compras).
-- Se incluye si CTACTE > 0 (crédito normal) O si tiene algún pago registrado en RELACIONESCTASCTES
-- (caso CONALLISON: CTACTE=0 pero el operador crea OPs y las imputa a las facturas).
-- Esto excluye compras contado genuinas (CTACTE=0 y sin imputaciones) que son falsos positivos.
-- EMPR0023 no tiene RELACIONESCTASCTES; se cae al criterio CTACTE<>0.

CREATE OR ALTER VIEW dbo.vw_Compras_FacturasPendientes AS

WITH Empresas AS (
    SELECT Empresa, NombreEmpresa FROM dbo.Config_Empresas
)

SELECT
    'EMPR0001'  AS EmpresaId,
    ce.NombreEmpresa,
    lc.CODIGO   AS CodigoFactura,
    lc.PROVEEDOR AS CodigoProveedor,
    e.NOMBRE    AS NombreProveedor,
    e.CUIT,
    lc.COMPROB  AS CodigoComprobante,
    cc.NOMBRE   AS TipoComprobante,
    lc.PTOEMISOR,
    lc.NUMERO,
    RIGHT('0000' + CAST(lc.PTOEMISOR AS nvarchar(10)), 4) + '-'
        + RIGHT('00000000' + CAST(lc.NUMERO AS nvarchar(20)), 8) AS NroComprobante,
    lc.FECHA    AS FechaFactura,
    lc.VENCE    AS FechaVencimiento,
    lc.TOTAL,
    lc.CTACTE                                          AS ImporteCtaCte,
    ISNULL(p.TotalPagado, 0)                           AS TotalPagado,
    lc.TOTAL - ISNULL(p.TotalPagado, 0)                AS SaldoPendiente,
    lc.MONEDA,
    lc.TIPOCAMBIO,
    DATEDIFF(day, lc.VENCE, CAST(GETDATE() AS date)) AS DiasAtraso,
    lc.PERIODO,
    lc.COMENTARIO
FROM EMPR0001.OFICIAL_LIBROCOMPRAS lc
JOIN Empresas ce ON ce.Empresa = 'EMPR0001'
LEFT JOIN EMPR0001.OFICIAL_ENTIDADES e ON e.CODIGO = lc.PROVEEDOR
LEFT JOIN EMPR0001.OFICIAL_CLASECOMPROBANTES cc ON cc.CODIGO = lc.COMPROB
LEFT JOIN (
    SELECT COMPRA, SUM(IMPORTE) AS TotalPagado
    FROM EMPR0001.OFICIAL_RELACIONESCTASCTES
    WHERE FONDO <> '0'
    GROUP BY COMPRA
) p ON p.COMPRA = lc.CODIGO
WHERE lc.TOTAL - ISNULL(p.TotalPagado, 0) > 0.01
      AND (lc.CTACTE > 0 OR ISNULL(p.TotalPagado, 0) > 0)

UNION ALL

