    RIGHT('0000'+CAST(lc.PTOEMISOR AS nvarchar(10)),4)+'-'+RIGHT('00000000'+CAST(lc.NUMERO AS nvarchar(20)),8),
    lc.FECHA, lc.VENCE, lc.TOTAL,
